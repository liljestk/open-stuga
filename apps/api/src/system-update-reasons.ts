export type CanonicalSystemUpdateReason = keyof typeof CURRENT_SYSTEM_UPDATE_REASON_CODE_GROUPS;

const CURRENT_SYSTEM_UPDATE_REASON_MAP: Readonly<Record<string, CanonicalSystemUpdateReason>> =
  Object.fromEntries(
    Object.entries(CURRENT_SYSTEM_UPDATE_REASON_CODE_GROUPS).flatMap(([canonicalReason, codes]) => (
      codes.map((code) => [code, canonicalReason as CanonicalSystemUpdateReason])
    )),
  );

export function canonicalSystemUpdateReason(reason: string | null | undefined): string | null {
  if (!reason) return null;
  return Object.prototype.hasOwnProperty.call(CURRENT_SYSTEM_UPDATE_REASON_MAP, reason)
    ? CURRENT_SYSTEM_UPDATE_REASON_MAP[reason]!
    : reason;
}
